def generate():
    profiles = []
    formats = ['свадьба', 'той', 'корпоратив', 'конференция', 'юбилей', 'день рождения']
    for category, count, base in SPECS:
        for i in range(count):
            identifier = 'demo-{:03d}'.format(len(profiles) + 1)
            rng = random.Random(identifier)
            city = 'Алматы' if i % 3 != 2 else 'Астана'
            busy = []
            for n in range(100):
                day = date(2026, 9, 23) + timedelta(days=n)
                if rng.random() < (0.76 if day.month == 12 else 0.37):
                    busy.append(day.isoformat())
            # Intentional fixtures for reliable live demonstrations.
            if category == 'Ведущий' and city == 'Алматы':
                for day in ['2026-10-17', '2026-10-18']:
                    if day in busy:
                        busy.remove(day)
                busy.append('2026-10-18' if i % 2 == 0 else '2026-10-17')
            if category == 'Флорист' and city == 'Алматы' and '2026-10-17' in busy:
                busy.remove('2026-10-17')
            person = category in ['Ведущий', 'Фотограф', 'Видеограф', 'Ведущий церемонии', 'Инструменталист', 'DJ']
            name = (NAMES[i] + ' ' + ['С.', 'А.', 'К.'][i % 3]) if person else (category + ' «' + ['Sary', 'Aura', 'Samal', 'Aspan', 'Dala', 'Lumi', 'Orda', 'Arqa'][i % 8] + '»')
            descriptions = DETAILS.get(category, ['Индивидуальная подготовка к событию. Согласовывает концепцию и детали с организатором заранее.', 'Лаконичный современный стиль. Внимание к деталям и согласованному таймингу.', 'Акцент на семейные традиции и тёплую атмосферу. Возможна адаптация концепции под площадку.'])
